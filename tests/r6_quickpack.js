const {boot,wait,mk,html}=require('./h');
const {ok,done}=mk();
(async()=>{
 ok(/rel="manifest"/.test(html)&&/apple-touch-icon/.test(html)&&/apple-mobile-web-app-capable/.test(html),'head manifest+apple');
 ok(/data:image\/png;base64/.test(html),'inline PNG icon');
 const wAr=boot(),wEn=boot({lang:'en-US'});
 await wait(900);
 ok(wAr.eval('db.lang')==='ar','ar phone -> Arabic');
 ok(wEn.eval('db.lang')==='en','en phone -> English');
 const w=wAr,d=w.document;
 w.tab('settings'); await wait(50);
 ok(/المظهر/.test(d.getElementById('app').textContent)&&!/الوضع الليلي/.test(d.getElementById('app').textContent),'appearance row renamed');
 w.eval("sec.dark=true;saveSec();render()"); await wait(40);
 ok(d.body.classList.contains('dark'),'body.dark on');
 w.eval("sec.dark=false;saveSec();render()"); await wait(40);
 ok(!d.body.classList.contains('dark'),'dark off');
 w.eval("sec.enabled=true;sec.fps=[{id:'aa',wrap:'w'},{id:'bb',wrap:'x'}];render()"); await wait(40);
 w.tab('settings'); await wait(50);
 const st=d.getElementById('app').textContent;
 ok(/\(2\)/.test(st)&&/بصمة 1/.test(st)&&/بصمة 2/.test(st),'fps list');
 ok(!st.includes('undefined'),'no undefined icon');
 w.eval("fpDel(1)"); await wait(40);
 ok(w.eval('sec.fps.length')===1,'fpDel');
 w.eval("fpDel(0)"); await wait(40);
 ok(w.eval('sec.fps.length')===0&&w.eval('sec.credId')===null,'fpDel clears');
 ok(w.eval("S_lock()").includes('fpUnlock')===false,'lock no fp btn without fps');
 w.eval("sec.fps=[{id:'aa',wrap:'w'}]");
 ok(w.eval("S_lock()").includes('fpUnlock'),'lock fp btn with fps');
 done();
})().catch(e=>{console.log('ERROR:',e);process.exit(1)});
