const {boot,wait,mk}=require('./h');
const w=boot(),d=w.document;const {ok,done}=mk();
const txt=()=>d.getElementById('app').textContent;
const rows=()=>[...d.querySelectorAll('#clist2 .litem')].map(e=>e.querySelector('b')?e.querySelector('b').textContent:'');
(async()=>{
 await wait(1000);
 w.tab('customers'); await wait(60);
 const sr=d.querySelector('.search');
 ok(sr&&sr.querySelector('#cfbtn'),'filter button in search row');
 ok(!d.getElementById('cfbtn').innerHTML.includes('999px'),'no badge initially');
 w.eval("openCustFilter()"); await wait(50);
 const st=d.getElementById('sheet').textContent;
 ok(/الحالة/.test(st)&&/الترتيب/.test(st),'sheet groups');
 ok(/عليه دين/.test(st)&&/متأخر/.test(st)&&/بدون دين/.test(st),'new status options');
 ok(!/مفتوح \(|جزئي \(|مسدد \(/.test(st),'old statuses removed');
 w.eval("setCSt('none')"); await wait(80);
 ok(rows().length===w.eval("DD().customers.filter(c=>!c.archived&&custOpen(c.id)<=0).length")&&rows().some(r=>r.includes('سارة')),'none -> settled customers');
 ok(d.getElementById('cfbtn').innerHTML.includes('999px'),'badge count shown');
 w.eval("setCSt('owed')"); await wait(80);
 ok(rows().length===3,'owed -> 3');
 w.eval("setCSt('all')"); await wait(80);
 ok(rows().length===5,'all -> 5');
 w.eval("setCSo('name')"); await wait(80);
 ok(rows().length===5,'name sort works');
 w.eval("setCSo('debt')"); await wait(80);
 ok(rows()[0].includes('أبو خالد'),'debt sort pinned first');
 w.eval("ui.f={status:'all',period:'all',sort:'recent',near:false,over:false};render()"); await wait(80);
 ok(rows().length===5&&!d.getElementById('cfbtn').innerHTML.includes('999px'),'reset');
 w.eval("closeSheet()");
 ok(/عليهم دين/.test(txt())&&/إجمالي الديون/.test(txt()),'summary strip new wording');
 w.eval("ui.cq='محمد';document.getElementById('clist2').innerHTML=custListBody()"); await wait(30);
 ok(rows().length===1&&rows()[0].includes('محمد'),'search');
 w.eval("ui.cq='';render()"); await wait(60);
 ok(!d.querySelector('#clist2 .litem').getAttribute('onpointerdown'),'row long-press removed per UX decision');
 ok(d.querySelector('#clist2 .litem .hbtn').getAttribute('aria-label')!==null,'row menu button labelled');
 done();
})().catch(e=>{console.log('ERROR:',e);process.exit(1)});
